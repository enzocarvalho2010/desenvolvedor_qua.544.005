# lista de cidades
cidades = ['Goiás','Brasília','São Paulo','Cuiabá','Itaquaquecetuba']

# ordena a lista
cidades.sort()

# exibe uma lista em ordem alfabética
for cidade in cidades:
    print(cidade)

print()
# reverte a lista
cidades.sort(reverse=True)

# exibe uma lista em ordem reversa
for cidade in cidades:
    print(cidade)